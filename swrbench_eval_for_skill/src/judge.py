"""LLM-as-Judge implementation adapted from SWR-Bench."""
import json
import os
from typing import Any, Dict, Optional

from src import config
from src.dataset import format_ground_truth_changes, format_timeline, is_clean_pr
from src.llm_client import run_chat
from loguru import logger


def _load_prompt(name: str) -> str:
    path = os.path.join(config.PROMPT_DIR, name)
    with open(path, "r", encoding="utf-8") as f:
        return f.read()


# Load prompt templates at import time.
CHANGE_PROMPT_TEMPLATE = _load_prompt("judge_eval_change.txt")
CLEAN_PROMPT_TEMPLATE = _load_prompt("judge_eval_clean.txt")


def _output_schema(is_change: bool) -> Dict[str, Any]:
    base = {
        "type": "json_schema",
        "json_schema": {
            "name": "evaluation",
            "strict": True,
            "schema": {
                "type": "object",
                "properties": {
                    "identified_as_good": {"type": "string"},
                    "pred_points": {
                        "type": "array",
                        "items": {
                            "type": "object",
                            "properties": {
                                "id": {"type": "string"},
                                "description": {"type": "string"},
                                "change_category": {"type": "string"},
                                "severity_score": {"type": "integer"},
                            },
                            "required": ["id", "description", "change_category", "severity_score"],
                            "additionalProperties": False,
                        },
                    },
                },
                "required": ["identified_as_good", "pred_points"],
                "additionalProperties": False,
            },
        },
    }
    if is_change:
        base["json_schema"]["schema"]["properties"]["gt_points"] = {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "id": {"type": "string"},
                    "description": {"type": "string"},
                    "change_category": {"type": "string"},
                    "hit": {"type": "string"},
                    "hit_by": {"type": "string"},
                },
                "required": ["id", "description", "change_category", "hit", "hit_by"],
                "additionalProperties": False,
            },
        }
        base["json_schema"]["schema"]["required"].append("gt_points")
    return base


def _build_change_prompt(item: Dict[str, Any], review: str) -> str:
    ground_truth_reviews = format_timeline(item)
    changes_description = format_ground_truth_changes(item)
    return CHANGE_PROMPT_TEMPLATE.format(
        pr_title=item.get("pr_title", ""),
        pr_statement=item.get("pr_statement", ""),
        ground_truth_reviews=ground_truth_reviews,
        changes_description=changes_description,
        pred_review=review,
    )


def _build_clean_prompt(item: Dict[str, Any], review: str) -> str:
    return CLEAN_PROMPT_TEMPLATE.format(
        pr_title=item.get("pr_title", ""),
        pr_statement=item.get("pr_statement", ""),
        pred_review=review,
    )


def _parse_judge_result(raw: str, is_change: bool) -> Optional[Dict[str, Any]]:
    try:
        result = json.loads(raw)
    except json.JSONDecodeError as e:
        logger.error(f"Judge returned invalid JSON: {e}")
        return None

    if result.get("identified_as_good") not in ("YES", "NO"):
        logger.error(f"Invalid identified_as_good value: {result.get('identified_as_good')}")
        return None

    if not isinstance(result.get("pred_points"), list):
        logger.error("pred_points is not a list")
        return None

    for point in result["pred_points"]:
        point["change_category"] = point.get("change_category", "").split(" ")[0]
        point["severity_score"] = int(point.get("severity_score", 0))

    if is_change:
        if not isinstance(result.get("gt_points"), list):
            logger.error("gt_points is not a list")
            return None
        for gt in result["gt_points"]:
            if gt.get("hit") not in ("YES", "NO"):
                logger.error(f"Invalid hit value: {gt.get('hit')}")
                return None

    return result


def judge_pr(item: Dict[str, Any], review: str, max_retries: int = config.JUDGE_MAX_RETRIES) -> Optional[Dict[str, Any]]:
    """Run the LLM judge on a single PR review.

    Args:
        item: Raw dataset item.
        review: The review generated by the skill under test.
        max_retries: Number of retries if parsing fails.

    Returns:
        Parsed judge result dict, or None if all retries failed.
    """
    is_change = not is_clean_pr(item)
    prompt = _build_change_prompt(item, review) if is_change else _build_clean_prompt(item, review)
    schema = _output_schema(is_change)

    messages = [{"role": "user", "content": prompt}]
    for attempt in range(max_retries):
        raw = run_chat(
            model=config.JUDGE_MODEL,
            messages=messages,
            temperature=config.JUDGE_TEMPERATURE,
            max_tokens=config.JUDGE_MAX_TOKENS,
            response_format=schema,
            max_retries=2,
        )
        if raw is None:
            logger.warning(f"Judge call failed (attempt {attempt + 1})")
            continue

        result = _parse_judge_result(raw, is_change)
        if result is not None:
            return result
        logger.warning(f"Judge result parsing failed (attempt {attempt + 1}), retrying...")

    logger.error(f"Failed to judge PR {item.get('instance_id')} after {max_retries} attempts")
    return None
